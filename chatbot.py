def classify_intent(user_message):
    """
    Classifies user intent by splitting messages and keywords into words
    and finding the intent with the highest number of common words.
    This is more flexible than simple substring matching.
    """
    text_words = set(user_message.lower().split())
    best_intent = None
    best_score = 0
    
    for intent, keywords in INTENT_KEYWORDS.items():
        score = 0
        for kw_phrase in keywords:
            kw_words = set(kw_phrase.split())
            # Find common words between user message and keyword phrase
            common_words = text_words.intersection(kw_words)
            # Add the number of common words to the score
            score += len(common_words)
        
        # The intent with the highest score wins
        if score > best_score:
            best_score = score
            best_intent = intent
            
    return best_intent


# ---------- Routes ----------
@app.route("/")
def serve_html():
    return send_from_directory(os.getcwd(), "Dashboard.html")


@app.route("/chat", methods=["POST"])
def chat():
    data = request.get_json()
    user_msg = data.get("message", "")
    intent = classify_intent(user_msg)

    if intent and intent in INTENT_RESPONSES:
        reply = random.choice(INTENT_RESPONSES[intent])
    else:
        reply = "🤔 I'm not sure I understood that. Could you rephrase?"

    return jsonify({"reply": reply})


